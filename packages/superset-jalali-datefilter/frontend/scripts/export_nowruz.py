#!/usr/bin/env python3
"""Write the JS Nowruz table and the Python/JS parity fixture.

The fixture covers every day of 1390–1420 plus Nowruz ± 2 days for every
year in the table. Expected dates come from ``calendar.py``, not from a
second implementation.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "packages" / "superset-jalali-sql" / "src"))

from superset_jalali_sql.calendar import NOWRUZ_DATES, g2j  # noqa: E402
from superset_jalali_sql.nowruz import NOWRUZ  # noqa: E402


def collect_days() -> list[dict[str, int | str]]:
    seen: set[str] = set()
    ordered: list[str] = []

    def add(day) -> None:
        iso = day.isoformat()
        if iso not in seen:
            seen.add(iso)
            ordered.append(iso)

    start = NOWRUZ_DATES[1390]
    end = NOWRUZ_DATES[1421]
    cursor = start
    while cursor < end:
        add(cursor)
        cursor += timedelta(days=1)

    for year in sorted(NOWRUZ_DATES):
        if year == max(NOWRUZ_DATES):
            continue
        nowruz = NOWRUZ_DATES[year]
        for delta in range(-2, 3):
            day = nowruz + timedelta(days=delta)
            if day < NOWRUZ_DATES[min(NOWRUZ_DATES)] or day >= NOWRUZ_DATES[max(NOWRUZ_DATES)]:
                continue
            add(day)

    rows = []
    for iso in ordered:
        jy, jm, jd = g2j(__import__("datetime").date.fromisoformat(iso))
        rows.append({"g": iso, "jy": jy, "jm": jm, "jd": jd})
    return rows


def render_ts() -> str:
    body = ",\n".join(f"  {year}: {json.dumps(iso)}" for year, iso in sorted(NOWRUZ.items()))
    return (
        "// Generated by scripts/export_nowruz.py from nowruz.py. Do not edit.\n"
        f"export const NOWRUZ: Record<number, string> = {{\n{body},\n}};\n"
    )


def main() -> None:
    frontend = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-ts", type=Path, default=frontend / "src" / "nowruz.generated.ts")
    parser.add_argument(
        "--out-fixture",
        type=Path,
        default=frontend / "test" / "fixtures" / "days.json",
    )
    args = parser.parse_args()
    args.out_ts.parent.mkdir(parents=True, exist_ok=True)
    args.out_fixture.parent.mkdir(parents=True, exist_ok=True)
    args.out_ts.write_text(render_ts(), encoding="utf-8")
    args.out_fixture.write_text(json.dumps(collect_days(), ensure_ascii=False), encoding="utf-8")
    print(f"wrote {args.out_ts} and {args.out_fixture}")


if __name__ == "__main__":
    main()
