-- Sample business schema. Superset must not change it; this stands in for a
-- database we only receive SELECT on.
CREATE SCHEMA IF NOT EXISTS sales;

CREATE TABLE sales.regions (
    code text PRIMARY KEY,
    name_fa text NOT NULL
);

CREATE TABLE sales.branches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_code text NOT NULL REFERENCES sales.regions (code),
    name_fa text NOT NULL
);

CREATE TABLE sales.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_fa text NOT NULL,
    category_fa text NOT NULL
);

CREATE TABLE sales.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES sales.branches (id),
    product_id integer NOT NULL REFERENCES sales.products (id),
    quantity integer NOT NULL,
    amount numeric(14, 2) NOT NULL,
    created_at timestamp NULL,
    status text NOT NULL
);

CREATE INDEX orders_created_at_idx ON sales.orders (created_at);
CREATE INDEX orders_branch_id_idx ON sales.orders (branch_id);
