#!/usr/bin/env python3
"""Build ``nowruz.py`` from two independent Jalali libraries.

The runtime never imports those libraries. They are pinned because a newer
persiantools disagrees with jdatetime from year 1503 onward. The script fails
if the two libraries disagree on 1 Farvardin for any year in range.

Year 1552 is stored only as the exclusive end sentinel: Esfand of 1551 and the
last convertible day need the next Nowruz.
"""

from __future__ import annotations

import argparse
import datetime as dt
from importlib.metadata import version
from pathlib import Path

import jdatetime
from persiantools.jdatetime import JalaliDate

JDATETIME_VERSION = "6.1.0"
PERSIANTOOLS_VERSION = "4.0.0"
FIRST_YEAR = 1350
LAST_YEAR = 1551  # last convertible year; the table also stores LAST_YEAR + 1

ANCHORS = {
    1403: dt.date(2024, 3, 20),
    1404: dt.date(2025, 3, 21),
    1405: dt.date(2026, 3, 21),
}


def nowruz_jdatetime(year: int) -> dt.date:
    return jdatetime.date(year, 1, 1).togregorian()


def nowruz_persiantools(year: int) -> dt.date:
    return JalaliDate(year, 1, 1).to_gregorian()


def build_table() -> dict[int, str]:
    if version("jdatetime") != JDATETIME_VERSION:
        raise SystemExit(
            f"jdatetime {version('jdatetime')} != required {JDATETIME_VERSION}"
        )
    if version("persiantools") != PERSIANTOOLS_VERSION:
        raise SystemExit(
            f"persiantools {version('persiantools')} != required {PERSIANTOOLS_VERSION}"
        )

    table: dict[int, str] = {}
    for year in range(FIRST_YEAR, LAST_YEAR + 2):
        left = nowruz_jdatetime(year)
        right = nowruz_persiantools(year)
        if left != right:
            raise SystemExit(
                f"Nowruz disagreement for {year}: jdatetime={left} persiantools={right}"
            )
        table[year] = left.isoformat()

    for year, expected in ANCHORS.items():
        if table[year] != expected.isoformat():
            raise SystemExit(f"anchor {year} is {table[year]}, expected {expected}")

    # 1403 is a leap year: 1403/12/30 == the day before Nowruz 1404.
    leap_end = dt.date.fromisoformat(table[1404]) - dt.timedelta(days=1)
    if leap_end != dt.date(2025, 3, 20):
        raise SystemExit(f"1403/12/30 resolved to {leap_end}, expected 2025-03-20")
    if (dt.date.fromisoformat(table[1404]) - dt.date.fromisoformat(table[1403])).days != 366:
        raise SystemExit("1403 is not a 366-day year")
    if (dt.date.fromisoformat(table[1405]) - dt.date.fromisoformat(table[1404])).days != 365:
        raise SystemExit("1404 is not a 365-day year")
    return table


def render(table: dict[int, str]) -> str:
    lines = [
        '"""Nowruz (1 Farvardin) of each Jalali year, as a Gregorian ISO date.',
        "",
        "Generated by tools/generate_nowruz.py.",
        f"Libraries: jdatetime=={JDATETIME_VERSION}, persiantools=={PERSIANTOOLS_VERSION}.",
        "Both libraries agreed on every year. Do not edit by hand.",
        "",
        f"Years {FIRST_YEAR}..{LAST_YEAR} are convertible.",
        f"{LAST_YEAR + 1} is the exclusive end sentinel (Nowruz after the last year).",
        "Anchors: 1403/01/01 = 2024-03-20, 1404/01/01 = 2025-03-21,",
        "1405/01/01 = 2026-03-21, 1403/12/30 = 2025-03-20.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "NOWRUZ: dict[int, str] = {",
    ]
    for year in sorted(table):
        lines.append(f'    {year}: "{table[year]}",')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "packages"
        / "superset-jalali-sql"
        / "src"
        / "superset_jalali_sql"
        / "nowruz.py",
    )
    args = parser.parse_args()
    text = render(build_table())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
